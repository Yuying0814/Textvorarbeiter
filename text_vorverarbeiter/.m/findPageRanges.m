function [regIdx,result] = findPageRanges(pages, option)
%Score pages based on keyword counts according to the selected option,and extract the pages most relevant to that option.

    %% Initialization
    keywords = selectKeyword(option);
    result = struct();
    featureCountsArray = zeros(1,numel(pages));
    firstTitleLikePage = 0;
    
    %% 
    for i = 1:numel(pages)
        text = pages(i).markdown;
        tables = pages(i).tables;
        titleCount = 0;
        featureCounts = 0;
        if ~isempty(tables)
            for j = 1:numel(tables)
                table = tables(j).content;
                text = [text newline table];
            end
        end
        text = lower(text);
        
        titleCount = searchKeywords(text,keywords.title);
        featureCounts = searchKeywords(text,keywords.feature);
        disp(i); %-------------------debug---------------------------
        titleLike = titleCount ~=0;
        if titleLike && firstTitleLikePage ==0
            firstTitleLikePage = i;
        end
        result.pages(i).title_like = titleLike;
        result.pages(i).feature_counts = featureCounts;
        featureCountsArray(i) = featureCounts;
    end
    regIdx = selectRange(featureCountsArray,firstTitleLikePage);
end

