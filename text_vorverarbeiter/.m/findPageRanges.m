function count = searchKeywords(text,keywords)
    count = 0;
    for i=1:numel(keywords)
        match = regexp(text,keywords{i},'lineanchors');
        count = count + numel(match);
        match = regexp(text,keywords{i},'match'); % ------------debug
        disp(match); % -----------------------------------------debug
    end
end

function pageRange = selectRange(arrayCounts,firstTitleLikePage)
%Extract page ranges longer than n which allows gaps of up to m pages with zero keyword counts.
% the page range starts with the chapter title page when it exists.
% e.g. 6 Register Mapping

    m = 2; % Maximum number of consecutive zero-valued pages allowed.
    n = 2; % Mimimum number of consecutive nonzero-valued pages allowed.
    negativeMask = (arrayCounts <= 0);
    d = diff([0 negativeMask 0]);
    zStartIdx = find(d == 1);             
    zEndIdx = find(d == -1) - 1;   
    
    invalid = (zEndIdx - zStartIdx + 1) > m;
    invalidStart = zStartIdx(invalid);
    invalidEnd = zEndIdx(invalid);
    startIdx = 1;
    pageRange = {};
    
    for i = 1:numel(invalidStart)
        endIdx = invalidStart(i) - 1;
        
        if endIdx-startIdx +1 > n && startIdx <= endIdx
            pageRange{end+1} = [startIdx endIdx];
        end
        
        startIdx = invalidEnd(i)+1;
    end
    
    if numel(arrayCounts)-startIdx + 1 > n
        pageRange{end+1} = [startIdx numel(arrayCounts)];
    end
    
    if firstTitleLikePage ~= 0
        mask = true(1,numel(pageRange));
        
        for i = 1:numel(pageRange)
            if all(firstTitleLikePage>pageRange{i})
                % Remove page ranges located entirely before the first title-like page.
                mask(i) = false;;
            end
        end
        
        if ~isempty(pageRange)
            pageRange = pageRange(mask);
            if ~isempty(pageRange)
                % Replace the start-page of the first valid page range with
                % the first title-like page
                pageRange{1}(1) = firstTitleLikePage;
            end
        end
    end
    for i = 1:numel(pageRange)
        pageRange{i} = pageRange{i}(1):pageRange{i}(2);
    end
end